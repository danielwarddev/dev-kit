using System.Collections.Immutable;
using System.Composition;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CodeActions;
using Microsoft.CodeAnalysis.CodeFixes;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.FindSymbols;
using Microsoft.CodeAnalysis.Text;

namespace Dward.Godot.Analyzers.CodeFixes;

[ExportCodeFixProvider(LanguageNames.CSharp, Name = nameof(PrivateGodotExportCodeFixProvider)), Shared]
public class PrivateGodotExportCodeFixProvider : CodeFixProvider
{
    private const string Title = "Make exported member private";
    private static readonly FixAllProvider _fixAllProvider = FixAllProvider.Create(FixDocument);

    public override ImmutableArray<string> FixableDiagnosticIds => ["DWARDGD0001"];

    public override FixAllProvider GetFixAllProvider() => _fixAllProvider;

    public override async Task RegisterCodeFixesAsync(CodeFixContext context)
    {
        foreach (var diagnostic in context.Diagnostics)
        {
            var repairedDocument = await CreateRepair(context.Document, diagnostic.Location.SourceSpan, context.CancellationToken)
                .ConfigureAwait(false);
            if (repairedDocument is not null)
            {
                context.RegisterCodeFix(
                    CodeAction.Create(Title, _ => Task.FromResult(repairedDocument), equivalenceKey: Title), diagnostic);
            }
        }
    }

    private static async Task<Document?> CreateRepair(Document document, TextSpan span, CancellationToken cancellationToken)
    {
        var root = await document.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);
        var model = await document.GetSemanticModelAsync(cancellationToken).ConfigureAwait(false);
        var token = root?.FindToken(span.Start);
        var node = token?.Parent;
        if (root is null || model is null || token?.Span != span
            || node is not (VariableDeclaratorSyntax or PropertyDeclarationSyntax))
        {
            return null;
        }

        var symbol = model.GetDeclaredSymbol(node, cancellationToken);
        if (symbol is not (IFieldSymbol or IPropertySymbol) || symbol.DeclaredAccessibility == Accessibility.Private
            || symbol.ContainingType.TypeKind is not (TypeKind.Class or TypeKind.Struct)
            || symbol.IsAbstract || symbol.IsVirtual || symbol.IsOverride
            || !symbol.GetAttributes().Any(attribute => SymbolEqualityComparer.Default.Equals(
                attribute.AttributeClass, model.Compilation.GetTypeByMetadataName("Godot.ExportAttribute")))
            || document.Name.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || root.GetLeadingTrivia().ToFullString().IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
            || (document.FilePath is not null && document.Project.Solution.GetDocumentIdsWithFilePath(document.FilePath).Length != 1))
        {
            return null;
        }

        MemberDeclarationSyntax declaration;
        SyntaxTokenList modifiers;
        if (node is VariableDeclaratorSyntax { Parent.Parent: FieldDeclarationSyntax field })
        {
            // A modifier edit affects every variable in a field declaration.
            if (field.Declaration.Variables.Count != 1)
            {
                return null;
            }
            declaration = field;
            modifiers = field.Modifiers;
        }
        else if (node is PropertyDeclarationSyntax property
                 && symbol is IPropertySymbol { ExplicitInterfaceImplementations.Length: 0 })
        {
            if (property.Modifiers.Any(SyntaxKind.RequiredKeyword)
                || property.Modifiers.Any(SyntaxKind.PartialKeyword)
                || property.AccessorList?.Accessors.Any(accessor => accessor.Modifiers.Count != 0) == true)
            {
                return null;
            }
            declaration = property;
            modifiers = property.Modifiers;
        }
        else
        {
            return null;
        }

        if (modifiers.Any(SyntaxKind.RequiredKeyword))
        {
            return null;
        }

        var accessModifiers = modifiers.Where(modifier => modifier.IsKind(SyntaxKind.PublicKeyword)
            || modifier.IsKind(SyntaxKind.ProtectedKeyword) || modifier.IsKind(SyntaxKind.InternalKeyword)
            || modifier.IsKind(SyntaxKind.PrivateKeyword)).ToArray();
        if (accessModifiers.Length == 0)
        {
            return null;
        }

        var first = accessModifiers[0];
        var privateModifier = SyntaxFactory.Token(first.LeadingTrivia, SyntaxKind.PrivateKeyword, first.TrailingTrivia);
        var repairedDeclaration = declaration.ReplaceToken(first, privateModifier);
        foreach (var extra in accessModifiers.Skip(1))
        {
            var current = repairedDeclaration.ChildTokens().Single(candidate => candidate.RawKind == extra.RawKind);
            var next = current.GetNextToken();
            var trivia = current.LeadingTrivia.AddRange(current.TrailingTrivia
                .SkipWhile(item => item.IsKind(SyntaxKind.WhitespaceTrivia))).AddRange(next.LeadingTrivia);
            repairedDeclaration = repairedDeclaration.ReplaceToken(next, next.WithLeadingTrivia(trivia));
            var currentModifiers = repairedDeclaration switch
            {
                FieldDeclarationSyntax changedField => changedField.Modifiers,
                PropertyDeclarationSyntax changedProperty => changedProperty.Modifiers,
                _ => throw new InvalidOperationException("Unsupported export declaration.")
            };
            var modifierIndex = currentModifiers.IndexOf(currentModifiers.Single(candidate => candidate.RawKind == extra.RawKind));
            repairedDeclaration = repairedDeclaration switch
            {
                FieldDeclarationSyntax changedField => changedField.WithModifiers(currentModifiers.RemoveAt(modifierIndex)),
                PropertyDeclarationSyntax changedProperty => changedProperty.WithModifiers(currentModifiers.RemoveAt(modifierIndex)),
                _ => throw new InvalidOperationException("Unsupported export declaration.")
            };
        }

        var repairedDocument = document.WithSyntaxRoot(root.ReplaceNode(declaration, repairedDeclaration));
        var solution = document.Project.Solution;
        var references = await SymbolFinder.FindReferencesAsync(symbol, solution, cancellationToken).ConfigureAwait(false);
        foreach (var reference in references.SelectMany(group => group.Locations))
        {
            if (reference.Document is SourceGeneratedDocument)
            {
                var generatedModel = await reference.Document.GetSemanticModelAsync(cancellationToken).ConfigureAwait(false);
                var enclosingType = generatedModel?.GetEnclosingSymbol(reference.Location.SourceSpan.Start, cancellationToken)?.ContainingType;
                while (enclosingType is not null && !SymbolEqualityComparer.Default.Equals(enclosingType, symbol.ContainingType))
                {
                    enclosingType = enclosingType.ContainingType;
                }
                if (enclosingType is null)
                {
                    return null;
                }
                continue;
            }
            if (reference.IsImplicit || reference.IsCandidateLocation)
            {
                return null;
            }
            var changedReferenceDocument = repairedDocument.Project.Solution.GetDocument(reference.Document.Id);
            if (changedReferenceDocument is null)
            {
                return null;
            }
            var changes = await changedReferenceDocument.GetTextChangesAsync(reference.Document, cancellationToken).ConfigureAwait(false);
            var offset = changes.Where(change => change.Span.End <= reference.Location.SourceSpan.Start)
                .Sum(change => (change.NewText?.Length ?? 0) - change.Span.Length);
            var changedRoot = await changedReferenceDocument.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);
            var changedModel = await changedReferenceDocument.GetSemanticModelAsync(cancellationToken).ConfigureAwait(false);
            var referenceNode = changedRoot?.FindToken(reference.Location.SourceSpan.Start + offset, findInsideTrivia: true).Parent;
            var changedSymbol = referenceNode is null ? null : changedModel?.GetSymbolInfo(referenceNode, cancellationToken).Symbol;
            if (changedSymbol is null
                || changedSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) != symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                || changedSymbol.ContainingType?.OriginalDefinition.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                    != symbol.ContainingType.OriginalDefinition.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                || !changedSymbol.ContainingAssembly.Identity.Equals(symbol.ContainingAssembly.Identity))
            {
                return null;
            }
        }

        var dependentProjects = solution.GetProjectDependencyGraph().GetProjectsThatTransitivelyDependOnThisProject(document.Project.Id);
        foreach (var projectId in dependentProjects.Prepend(document.Project.Id))
        {
            var originalProject = solution.GetProject(projectId)
                ?? throw new InvalidOperationException("Missing original export consumer project.");
            var repairedProject = repairedDocument.Project.Solution.GetProject(projectId)
                ?? throw new InvalidOperationException("Missing repaired export consumer project.");
            var originalCompilation = await originalProject.GetCompilationAsync(cancellationToken).ConfigureAwait(false);
            var repairedCompilation = await repairedProject.GetCompilationAsync(cancellationToken).ConfigureAwait(false);
            if (originalCompilation is null || repairedCompilation is null
                || originalCompilation.GetDiagnostics(cancellationToken).Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
                || repairedCompilation.GetDiagnostics(cancellationToken).Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error))
            {
                return null;
            }

            foreach (var tree in originalCompilation.SyntaxTrees)
            {
                var treeRoot = await tree.GetRootAsync(cancellationToken).ConfigureAwait(false);
                var treeModel = originalCompilation.GetSemanticModel(tree);
                foreach (var name in treeRoot.DescendantNodes().OfType<SimpleNameSyntax>()
                    .Where(name => name.Identifier.ValueText == symbol.Name))
                {
                    if (name.Parent is NameColonSyntax or NameEqualsSyntax)
                    {
                        continue;
                    }
                    var binding = treeModel.GetSymbolInfo(name, cancellationToken);
                    if (binding.Symbol is null && binding.CandidateSymbols.Length == 0
                        && treeModel.GetMemberGroup(name, cancellationToken).Length == 0)
                    {
                        return null;
                    }
                }
            }
        }

        return repairedDocument;
    }

    private static async Task<Document?> FixDocument(FixAllContext context, Document document, ImmutableArray<Diagnostic> diagnostics)
    {
        var root = await document.GetSyntaxRootAsync(context.CancellationToken).ConfigureAwait(false);
        if (root is null)
        {
            return null;
        }
        var targets = diagnostics.Select(diagnostic => root.FindNode(diagnostic.Location.SourceSpan, getInnermostNodeForTie: true))
            .Distinct().OrderBy(target => target.SpanStart).ToArray();
        var annotations = targets.ToDictionary(target => target, _ => new SyntaxAnnotation());
        root = root.ReplaceNodes(targets, (original, rewritten) => rewritten.WithAdditionalAnnotations(annotations[original]));
        document = document.WithSyntaxRoot(root);
        foreach (var original in targets)
        {
            root = await document.GetSyntaxRootAsync(context.CancellationToken).ConfigureAwait(false)
                ?? throw new InvalidOperationException("Missing export syntax root.");
            var target = root.GetAnnotatedNodes(annotations[original]).Single();
            var identifier = target switch
            {
                VariableDeclaratorSyntax variable => variable.Identifier,
                PropertyDeclarationSyntax property => property.Identifier,
                _ => default
            };
            var repairedDocument = await CreateRepair(document, identifier.Span, context.CancellationToken).ConfigureAwait(false);
            if (repairedDocument is not null)
            {
                document = repairedDocument;
            }
        }
        return document;
    }
}
